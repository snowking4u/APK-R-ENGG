"""Java decompilation pipeline (Phase 03).

Turns the DEX files of a decoded Phase 02 project into browsable Java
sources:

    decoded project -> DEX discovery -> JADX -> decompiled/sources
    -> Java source discovery -> lightweight Java index

This module is pure orchestration: no Qt imports, no GUI state, safe to run
on a worker thread (``app/ui/jadx_worker.py``) or directly from tests.

Workspace layout produced here::

    project/
        original/                 pristine APK copy (never touched)
        decoded/                  Apktool output    (never modified)
        metadata/                 manifest info, DEX staging, index cache
        logs/
        decompiled/               <- generated by Phase 03
            sources/              JADX generated Java sources
            resources/            JADX generated resources
            dex/                  never used; DEX staging lives in metadata/

Only ``decompiled/`` (and read-only helpers under ``metadata/``) is written
by Phase 03. ``decoded/`` and ``original/`` are never modified, and no
content coming from the APK is ever executed.
"""

import json
import os
import shutil
import time

from app.core import logger
from app.core.dex_discovery import (discover_dex_files, discover_dex_in_apk,
                                    extract_dex_files, dex_summary)
from app.core.java_index import (INDEX_FILENAME, build_index, find_java_source_root,
                                 discover_java_sources, JavaIndex)
from app.core.jadx_runner import (decompile_with_jadx, find_jadx, jadx_status_text,
                                  jadx_missing_message)


DEFAULT_DECOMPILE_TIMEOUT = 900  # seconds; JADX is slow on large APKs

DECOMPILED_DIRNAME = "decompiled"
SOURCES_DIRNAME = "sources"
RESOURCES_DIRNAME = "resources"
INFO_FILENAME = "jadx_info.json"


class DecompileReport:
    """Summary of a Java decompilation attempt (successful or not)."""

    __slots__ = ("ok", "error", "status", "apk_path", "workspace_root",
                 "decoded_dir", "decompiled_dir", "sources_dir",
                 "resources_dir", "dex_dir", "dex_names", "dex_files",
                 "java_source_root", "java_sources", "index", "jadx_status",
                 "jadx_description", "return_code", "timed_out",
                 "tool_missing", "duration", "process_output", "reused",
                 "cleaned", "dex_count")

    def __init__(self):
        self.ok = False
        self.error = ""
        self.status = "Idle"          # Idle | Running | Completed | Failed |
                                      # Not configured | Reused
        self.apk_path = ""
        self.workspace_root = ""
        self.decoded_dir = ""
        self.decompiled_dir = ""
        self.sources_dir = ""
        self.resources_dir = ""
        self.dex_dir = ""
        self.dex_names = []
        self.dex_files = []
        self.java_source_root = ""
        self.java_sources = []
        self.index = None
        self.jadx_status = "Not configured"
        self.jadx_description = ""
        self.return_code = None
        self.timed_out = False
        self.tool_missing = False
        self.duration = 0.0
        self.process_output = ""
        self.reused = False
        self.cleaned = False
        self.dex_count = 0

    # -- convenience ----------------------------------------------------- #
    @property
    def java_source_count(self):
        return len(self.java_sources)

    def to_dict(self):
        data = {name: getattr(self, name) for name in self.__slots__}
        data["java_sources"] = list(self.java_sources)
        data["dex_names"] = list(self.dex_names)
        data["dex_files"] = list(self.dex_files)
        data["index"] = (self.index.summary() if self.index else {})
        return data


# ---------------------------------------------------------------------- #
# Workspace helpers
# ---------------------------------------------------------------------- #
def dex_staging_dir(workspace_root):
    """Directory holding the DEX copies extracted from the APK."""
    return os.path.join(workspace_root, "metadata", "dex")


def decompiled_root(workspace_root):
    """Absolute path of the generated decompilation directory."""
    return os.path.join(workspace_root, DECOMPILED_DIRNAME)


def _is_safe_to_remove(path, workspace_root):
    """Guard for recursive deletes: only ``<workspace>/decompiled``."""
    if not path or not workspace_root:
        return False
    target = os.path.abspath(path)
    root = os.path.abspath(workspace_root)
    return (os.path.basename(target) == DECOMPILED_DIRNAME
            and os.path.dirname(target).rstrip("\\/") == root.rstrip("\\/"))


def clean_decompiled_dir(workspace_root):
    """Remove only the generated decompilation directory.

    The original APK and the decoded project data are never touched.
    Returns True when the directory is gone afterwards.
    """
    target = decompiled_root(workspace_root)
    if not _is_safe_to_remove(target, workspace_root):
        message = "Refusing to remove unexpected path: %s" % target
        logger.error(message)
        return False
    if not os.path.exists(target):
        return True
    try:
        shutil.rmtree(target)
        logger.info("Removed previous decompilation output: %s" % target)
        return True
    except OSError as exc:
        message = "Could not remove previous decompilation output: %s" % exc
        logger.error(message)
        return False


def prepare_decompiled_dir(workspace_root, clean=False):
    """Create (or reuse) ``<workspace>/decompiled/{sources,resources}``.

    Returns ``(decompiled_dir, sources_dir, resources_dir, error)``.
    Never raises.
    """
    target = decompiled_root(workspace_root)
    sources = os.path.join(target, SOURCES_DIRNAME)
    resources = os.path.join(target, RESOURCES_DIRNAME)

    if clean:
        if not clean_decompiled_dir(workspace_root):
            return "", "", "", "Could not clean the decompilation directory."

    try:
        os.makedirs(target, exist_ok=True)
        os.makedirs(sources, exist_ok=True)
        os.makedirs(resources, exist_ok=True)
    except OSError as exc:
        message = "Could not create decompilation directory: %s" % exc
        logger.error(message)
        return "", "", "", message

    return target, sources, resources, ""


def _info_path(workspace_root):
    return os.path.join(workspace_root, "metadata", INFO_FILENAME)


def read_decompile_info(workspace_root):
    """Read the marker describing a previous successful decompilation."""
    path = _info_path(workspace_root)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return None


def write_decompile_info(workspace_root, payload):
    """Persist the decompilation marker (best effort)."""
    path = _info_path(workspace_root)
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2)
        return True
    except (OSError, TypeError, ValueError) as exc:
        logger.warning("Could not write decompilation info: %s" % exc)
        return False


def existing_output_is_valid(workspace_root, dex_files=None):
    """True when a previous decompilation output can be reused as-is.

    Valid means: the marker exists, its recorded DEX signature still
    matches the DEX files we would feed to JADX, and Java sources are
    actually present on disk.
    """
    info = read_decompile_info(workspace_root)
    if not info or not info.get("ok"):
        return False
    root = decompiled_root(workspace_root)
    if not os.path.isdir(root):
        return False
    if dex_files:
        recorded = list(info.get("dex_signature") or [])
        current = [os.path.basename(path) for path in dex_files]
        if sorted(recorded) != sorted(current):
            return False
    source_root = info.get("java_source_root") or ""
    if source_root and not discover_java_sources(source_root, skip_dirs=set()):
        return False
    if not find_java_source_root(root):
        return False
    return True


# ---------------------------------------------------------------------- #
# DEX input collection
# ---------------------------------------------------------------------- #
def collect_dex_inputs(apk_path="", workspace_root="", decoded_dir="",
                       dex_dir=""):
    """Resolve the actual DEX files JADX will receive.

    Priority: an explicitly provided directory > DEX files extracted from
    the (read-only) APK > DEX files that already exist in the decoded
    project. Returns ``(paths, names, error)``; never raises.
    """
    if dex_dir:
        paths = discover_dex_files(dex_dir)
        if paths:
            return paths, [os.path.basename(p) for p in paths], ""
        return [], [], "No DEX files found in %s" % dex_dir

    if apk_path and os.path.isfile(apk_path):
        if workspace_root:
            staging = dex_staging_dir(workspace_root)
            extracted, error = extract_dex_files(apk_path, staging)
            if extracted:
                return (extracted, [os.path.basename(p) for p in extracted], "")
            if error:
                return [], [], error
        names, error = discover_dex_in_apk(apk_path)
        if not names:
            return [], [], error or "No DEX files found in the APK."
        return [], names, ("DEX files were found in the APK but have not been "
                           "extracted; open the project again.")

    if decoded_dir:
        paths = discover_dex_files(decoded_dir)
        if paths:
            return paths, [os.path.basename(p) for p in paths], ""
        return [], [], ("No classes*.dex file found in %s. Decompile the APK "
                        "first so its DEX files become available."
                        % decoded_dir)

    return [], [], "No DEX input available for Java decompilation."


# ---------------------------------------------------------------------- #
# Pipeline
# ---------------------------------------------------------------------- #
def load_java_index(workspace_root, source_root, progress=None):
    """Build (or refresh) the Java index for an existing decompilation."""
    cache_path = os.path.join(workspace_root, "metadata", INDEX_FILENAME)
    index = JavaIndex.load(cache_path)
    if index and index.root == source_root and not index.stale_sources():
        logger.info("Java source index loaded from cache (%d sources)"
                    % index.source_count)
        return index
    if index:
        logger.info("Java source index refreshed (%d stale entries)"
                    % len(index.stale_sources()))
    index = build_index(source_root, progress=progress)
    index.save(cache_path)
    return index


def run_decompile(apk_path="", workspace_root="", decoded_dir="", dex_dir="",
                  dex_files=None, clean=False, reuse=True, timeout=None,
                  progress=None, stage=None):
    """Run the full Java decompilation pipeline (thread-safe).

    ``progress(current, total)`` and ``stage(text)`` are optional callbacks
    used by the UI worker; both are plain callables so the tests can use
    this function directly. Returns a :class:`DecompileReport`; never
    raises.
    """
    report = DecompileReport()
    started = time.time()
    report.apk_path = apk_path or ""
    report.workspace_root = workspace_root or ""
    report.decoded_dir = decoded_dir or ""
    report.status = "Running"

    def say(text):
        if stage:
            stage(text)

    try:
        tool = find_jadx()
        report.jadx_description = tool.description if tool else ""
        report.jadx_status = "Ready" if tool else "Not configured"

        if not workspace_root:
            report.error = "No project workspace available for Java output."
            report.status = "Failed"
            logger.error(report.error)
            return report
        if not os.path.isdir(workspace_root):
            report.error = "Project workspace not found: %s" % workspace_root
            report.status = "Failed"
            logger.error(report.error)
            return report

        logger.info("Java decompilation requested")

        # ---- DEX inputs ------------------------------------------------ #
        say("Discovering DEX files...")
        if dex_files:
            resolved = [str(path) for path in dex_files]
            names = [os.path.basename(path) for path in resolved]
            error = ""
        else:
            resolved, names, error = collect_dex_inputs(
                apk_path=apk_path, workspace_root=workspace_root,
                decoded_dir=decoded_dir, dex_dir=dex_dir)
        report.dex_files = resolved
        report.dex_names = names
        report.dex_count = len(resolved)
        if dex_dir:
            report.dex_dir = dex_dir
        elif apk_path:
            report.dex_dir = dex_staging_dir(workspace_root)

        if error:
            report.error = error
            report.status = "Failed"
            logger.error(error)
            return report
        if not resolved:
            report.error = "No DEX files available for Java decompilation."
            report.status = "Failed"
            logger.error(report.error)
            return report

        logger.info("DEX files discovered: %d (%s)"
                    % (len(resolved), dex_summary(resolved)))
        report.dex_count = len(resolved)

        if not tool:
            message = jadx_missing_message()
            report.error = message
            report.tool_missing = True
            report.status = "Not configured"
            report.jadx_status = "Not configured"
            logger.error("JADX not found")
            logger.error(message)
            return report

        # ---- reuse / (re)generate --------------------------------------- #
        say("Preparing Java decompilation...")
        reused = bool(reuse and not clean and existing_output_is_valid(
            workspace_root, resolved))

        if reused:
            target, sources, resources, error = prepare_decompiled_dir(
                workspace_root, clean=False)
            if error:
                report.error = error
                report.status = "Failed"
                logger.error(error)
                return report
            report.reused = True
            report.status = "Reused"
            logger.info("Existing decompilation output reused: %s" % sources)
        else:
            target, sources, resources, error = prepare_decompiled_dir(
                workspace_root, clean=True)
            if error:
                report.error = error
                report.status = "Failed"
                logger.error(error)
                return report
            report.cleaned = True

            say("Starting JADX...")
            result = decompile_with_jadx(resolved, target, tool=tool,
                                         timeout=timeout or DEFAULT_DECOMPILE_TIMEOUT)
            report.return_code = result.return_code
            report.timed_out = result.timed_out
            report.duration = result.duration
            report.process_output = result.output_tail(600)
            if result.timed_out:
                report.error = ("JADX timed out after %d seconds."
                                % (timeout or DEFAULT_DECOMPILE_TIMEOUT))
                report.status = "Failed"
                logger.error(report.error)
                return report
            if result.error or result.return_code != 0:
                detail = result.output_tail(600)
                report.error = result.error or ("JADX failed (exit %s). %s"
                                                % (result.return_code, detail))
                report.status = "Failed"
                logger.error("JADX process failed")
                logger.error(report.error)
                return report

        report.decompiled_dir = target
        report.sources_dir = sources
        report.resources_dir = resources

        # ---- Java source discovery -------------------------------------- #
        say("Decompiling classes...")
        source_root = find_java_source_root(target)
        report.java_source_root = source_root
        if not source_root:
            report.error = ("JADX finished but no Java sources were found in "
                            "%s." % target)
            report.status = "Failed"
            logger.error(report.error)
            return report

        files = discover_java_sources(source_root)
        report.java_sources = files
        logger.info("Java source discovery completed: %d file(s)"
                    % len(files))
        if not files:
            report.error = "JADX produced no Java source files."
            report.status = "Failed"
            logger.error(report.error)
            return report

        # ---- index ------------------------------------------------------ #
        say("Indexing Java sources...")
        cache_path = os.path.join(workspace_root, "metadata", INDEX_FILENAME)
        index = JavaIndex.load(cache_path)
        if index and index.root == source_root and not index.stale_sources():
            logger.info("Java source index loaded from cache (%d sources)"
                        % index.source_count)
        else:
            index = build_index(source_root, progress=progress)
            index.save(cache_path)
        report.index = index

        write_decompile_info(workspace_root, {
            "ok": True,
            "jadx": report.jadx_description,
            "dex_signature": [os.path.basename(path) for path in resolved],
            "dex_dir": report.dex_dir,
            "java_source_root": source_root,
            "java_sources": len(files),
            "java_methods": index.method_count,
            "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
        })

        report.ok = True
        report.status = "Completed"
        report.duration = report.duration or (time.time() - started)
        logger.info("Java decompilation completed: %d source file(s), %d method(s)"
                    % (index.source_count, index.method_count))
    except Exception as exc:  # never take the UI down
        report.error = "Java decompilation failed unexpectedly: %s" % exc
        report.status = "Failed"
        logger.error(report.error)

    return report


def load_existing_decompilation(workspace_root, progress=None):
    """Load Java sources + index produced by an earlier decompilation.

    Used when a project is reopened so the tree/editor work without
    running JADX again. Returns a :class:`DecompileReport` with
    ``status = "Completed"`` when sources were found, otherwise an empty
    report with a safe status.
    """
    report = DecompileReport()
    report.workspace_root = workspace_root or ""
    tool = find_jadx()
    report.jadx_description = tool.description if tool else ""
    report.jadx_status = "Ready" if tool else "Not configured"

    target = decompiled_root(workspace_root) if workspace_root else ""
    if not target or not os.path.isdir(target):
        report.status = "Idle"
        return report

    report.decompiled_dir = target
    report.sources_dir = os.path.join(target, SOURCES_DIRNAME)
    report.resources_dir = os.path.join(target, RESOURCES_DIRNAME)

    source_root = find_java_source_root(target)
    if not source_root:
        report.status = "Idle"
        return report

    report.java_source_root = source_root
    report.java_sources = discover_java_sources(source_root)
    report.reused = True
    try:
        report.index = load_java_index(workspace_root, source_root,
                                       progress=progress)
    except Exception as exc:  # defensive: cache/index problems are not fatal
        logger.warning("Java index load failed: %s" % exc)
        report.index = None

    info = read_decompile_info(workspace_root) or {}
    report.dex_names = list(info.get("dex_signature") or [])
    report.ok = bool(report.java_sources)
    report.status = "Completed" if report.ok else "Idle"
    logger.info("Existing Java sources loaded: %d file(s)"
                % len(report.java_sources))
    return report